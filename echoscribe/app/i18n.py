TRANSLATIONS = {"en": _EN, "zh-CN": _ZH, "es": _ES}


def normalize_language(language: str) -> str:
    """Return a supported GUI language code, defaulting to English."""
    return language if language in TRANSLATIONS else "en"


def tr(language: str, key: str, **values: Any) -> str:
    """Translate a GUI key and interpolate named values."""
    catalog = TRANSLATIONS[normalize_language(language)]
    template = catalog.get(key, _EN.get(key, key))
    return template.format(**values)
